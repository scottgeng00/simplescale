def source_reference(text, source):
    """The first phrase referring to the source document, or None."""
    m = _META.search(text)
    if m:
        return m.group(0)
    for m in _REF.finditer(text):
        noun = (m.group(1) or m.group(2)).lower()
        if not re.search(rf"\b(?:the|this) {noun}\b", source, re.I):
            return m.group(0)
    return None


def finish_view(kind, text, source):
    """(final text, reject reason or None). Mix types unchanged; NEW_PROMPTS types reference-repaired, then rejected
    ("source_reference") if they still refer to the source."""
    if kind not in NEW_PROMPTS:
        return text, None
    text = repair_references(text)
    return text, "source_reference" if source_reference(text, source) else None


