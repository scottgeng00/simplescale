def fill_template(kind, rng):
    """(prompt, filled slots) for a NEW_PROMPTS type: each {slot} drawn uniformly from SLOTS."""
    tpl = NEW_PROMPTS[kind]
    fill = {k: rng.choice(v) for k, v in SLOTS.items() if "{" + k + "}" in tpl}
    for k, v in fill.items():
        tpl = tpl.replace("{" + k + "}", v)
    return tpl, fill


def planner_message(text):
    menu = "\n".join(f"- {k}: {MENU[k]}" for k in TYPES)
    return PLANNER.replace("{menu}", menu).replace("{document}", text)


_OBJ = re.compile(r"\{[^{}]*\}", re.S)
_PAIR = re.compile(r"[\"']?([A-Za-z][A-Za-z _-]*?)[\"']?\s*[:=]\s*[\"']?([0-2])\b")


def _key(k):
    return re.sub(r"[\s-]+", "_", str(k).strip().lower())


def parse_scores(reply):
    """{type: 0|1|2} for all 16 types from a planner reply (JSON object, else "name": score pairs), or None."""
    reply = re.sub(r"^.*?</think>", "", reply or "", flags=re.S)
    found = {}
    for m in _OBJ.finditer(reply):
        try:
            d = json.loads(m.group(0))
        except ValueError:
            continue
        if isinstance(d, dict):
            found.update({_key(k): v for k, v in d.items()})
    if not set(TYPES) <= set(found):
        found.update({_key(k): v for k, v in _PAIR.findall(reply) if _key(k) not in found})
    scores = {}
    for k in TYPES:
        v = found.get(k)
        if isinstance(v, bool) or str(v).strip() not in {"0", "1", "2"}:
            return None
        scores[k] = int(str(v).strip())
    return scores


def choose_types(rng, n=8, scores=None):
    """n distinct types: uniform without replacement, or weighted by planner scores (SCORE_WEIGHT) without
    replacement; if fewer than n types have weight > 0, all of them, then UNIVERSAL types not yet chosen (random
    order), then (only if still short) other types uniformly."""
    if scores is None:
        return rng.sample(TYPES, n)
    pool = {k: SCORE_WEIGHT[scores[k]] for k in TYPES if SCORE_WEIGHT[scores[k]] > 0}
    if len(pool) <= n:
        chosen = list(pool)
        rng.shuffle(chosen)
    else:
        chosen = []
        for _ in range(n):
            keys = list(pool)
            k = rng.choices(keys, weights=[pool[x] for x in keys])[0]
            chosen.append(k)
            del pool[k]
    for extra in (UNIVERSAL, TYPES):
        rest = [k for k in extra if k not in chosen]
        rng.shuffle(rest)
        chosen += rest[:n - len(chosen)]
    return chosen


