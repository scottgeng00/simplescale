def build_shim(directory):
    """Compile the LD_PRELOAD shim that makes connect()/sendto() fail; returns its path (None if gcc fails)."""
    src, so = os.path.join(directory, "noconnect.c"), os.path.join(directory, "noconnect.so")
    with open(src, "w") as f:
        f.write(_SHIM)
    r = subprocess.run(["gcc", "-shared", "-fPIC", "-O1", "-o", so, src], capture_output=True)
    return so if r.returncode == 0 else None


def _limits(cpu, mem):
    def f():
        os.setsid()
        resource.setrlimit(resource.RLIMIT_CPU, (cpu, cpu + 1))
        resource.setrlimit(resource.RLIMIT_AS, (mem, mem))
        resource.setrlimit(resource.RLIMIT_FSIZE, (16 << 20, 16 << 20))
        resource.setrlimit(resource.RLIMIT_NOFILE, (64, 64))
        resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    return f


def _run(cmd, cwd, stdin, timeout, shim, cpu=None, mem=2 << 30):
    """(returncode or "timeout", stdout, stderr) of a sandboxed command."""
    env = {"PATH": "/usr/bin:/bin", "HOME": cwd, "TMPDIR": cwd, "LANG": "C.UTF-8", "PYTHONDONTWRITEBYTECODE": "1"}
    if shim:
        env["LD_PRELOAD"] = shim
    p = subprocess.Popen(cmd, cwd=cwd, env=env, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                         preexec_fn=_limits(cpu or int(timeout) + 1, mem))
    try:
        out, err = p.communicate((stdin or "").encode(), timeout=timeout)
        rc = p.returncode
    except subprocess.TimeoutExpired:
        try:
            os.killpg(p.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        out, err = p.communicate()
        rc = "timeout"
    return rc, out[:_OUT_MAX].decode("utf-8", "replace"), err[-2000:].decode("utf-8", "replace")


def check_code(kind, text, lang, shim=None, timeout=10.0):
    """Execution check of a code / code_problem view requesting ``lang``. Returns {"status": ..., ...}:
    status "pass" (runs, exit 0; for code_problem with extractable example I/O also "match": bool), "unverified"
    (Java: no javac on the cluster), or a failure: "no_code", "wrong_language", "unsafe", "compile_error", "crash"
    (nonzero exit / signal), "timeout"."""
    blocks = code_blocks(text)
    if not blocks and kind == "code" and _looks_like(text, lang):  # the whole view is the program, unfenced
        blocks = [("", text, 0, len(text))]
    sol = solution_block(blocks, lang)
    if sol is None:
        return {"status": "no_code"}
    if sol == -1:
        return {"status": "wrong_language"}
    code = blocks[sol][1]
    res = {}
    stdin = None
    if kind == "code_problem":
        stdin, expected = example_io(text, blocks, sol)
        res.update(has_input=stdin is not None, has_output=expected is not None)
    if lang == "Java":
        return {"status": "unverified", **res}
    if _UNSAFE[lang].search(code):
        return {"status": "unsafe", **res}
    d = tempfile.mkdtemp(prefix="mix16code-")
    try:
        if lang == "Python":
            with open(os.path.join(d, "main.py"), "w") as f:
                f.write(code)
            rc, out, err = _run(["/usr/bin/python3", "-I", "main.py"], d, stdin, timeout, shim)
        else:
            with open(os.path.join(d, "main.c"), "w") as f:
                f.write(code)
            rc, _, err = _run(["gcc", "-std=c99", "-O0", "-w", "-o", "main", "main.c", "-lm"], d, None, 60, None, mem=4 << 30)
            if rc != 0:
                return {"status": "compile_error", "stderr": err[-500:], **res}
            rc, out, err = _run(["./main"], d, stdin, timeout, shim)
    finally:
        shutil.rmtree(d, ignore_errors=True)
    if rc == "timeout":
        return {"status": "timeout", **res}
    if rc != 0:
        return {"status": "crash", "returncode": rc, "stderr": err[-500:], **res}
    res["status"] = "pass"
    if kind == "code_problem" and stdin is not None and expected is not None:
        res["match"] = _norm(out) == _norm(expected)
    return res
