def code_blocks(text):
    """[(tag, code, start, end)] of the fenced blocks of a view."""
    return [(m.group(1).lower(), m.group(2), m.start(), m.end()) for m in _FENCE.finditer(text)]


def _looks_like(code, lang):
    pats = {"Python": r"^\s*(?:def |import |from \w+ import|print\()", "C": r"#include\s*<", "Java": r"\bclass\s+Main\b"}
    return re.search(pats[lang], code, re.M) is not None


def solution_block(blocks, lang):
    """Index of the solution among code_blocks: the longest block tagged with the language (else untagged and
    looking like it); None if there is none; -1 if the code is in another language."""
    tagged = [i for i, b in enumerate(blocks) if b[0] in LANG_TAGS[lang]]
    if not tagged:
        tagged = [i for i, b in enumerate(blocks) if not b[0] and _looks_like(b[1], lang)]
    if not tagged:
        other = [i for i, b in enumerate(blocks) if b[0] in _OTHER_TAGS or b[0] in {t for l, ts in LANG_TAGS.items() if l != lang for t in ts}]
        return -1 if other else None
    return max(tagged, key=lambda i: len(blocks[i][1]))


_LABEL = re.compile(r"^[ \t#>*_-]*(?:\d+[.)]\s*)?(?P<pre>[A-Za-z ]{0,25}?)\b(?P<io>input|output)s?\b(?P<post>[^:\n]{0,30}?)[*_ \t]*:?[*_ \t]*(?P<inline>[^\n]*)$",
                    re.I | re.M)
_LABEL_WORDS = re.compile(r"\b(?:example|sample|exact|expected|final|actual|program|test|for the example)\b", re.I)


def _section(text, end, blocks):
    """Content introduced by a label line ending at ``end``: a fenced block starting on the next non-empty line, else
    the following lines up to a blank line, a heading or a fence."""
    for tag, code, start, stop in blocks:
        if start >= end and not text[end:start].strip():
            return code
    lines = []
    for line in text[end:].lstrip("\n").split("\n"):
        if not line.strip() or line.lstrip().startswith(("#", "```", "**")):
            break
        lines.append(line)
    return "\n".join(lines) if lines else None


def example_io(text, blocks, sol):
    """(example input, expected output) of a code_problem view, either None when not extractable. Labels are short
    lines such as "Example Input:", "**Sample Output**", "Exact output for the example input:" (not "Input Format");
    the content is an inline value after the label (backticks stripped), the fenced block right after it, or the plain
    lines after it. The input is the last input label before the solution block; the output the last output label
    after the solution, else the last one before it."""
    sol_start, sol_end = blocks[sol][2], blocks[sol][3]
    inside = [(b[2], b[3]) for b in blocks]
    inp = out_before = out_after = None
    for m in _LABEL.finditer(text):
        if any(a <= m.start() < b for a, b in inside) or len(m.group(0)) > 120:
            continue
        label = (m.group("pre") or "") + " " + (m.group("post") or "")
        if re.search(r"format|constraint|specification|description", label + m.group("inline")[:20], re.I):
            continue
        if not _LABEL_WORDS.search(label) and (m.group("pre") or "").strip():
            continue
        inline = m.group("inline").strip().strip("*_ ")
        if inline.startswith("`") and inline.endswith("`") and len(inline) > 1:
            content = inline.strip("`")
        elif inline and not re.search(r"[.:]\s*$", inline) and len(inline) < 60 and not _LABEL_WORDS.search(inline):
            content = inline
        else:
            content = _section(text, m.end(), blocks)
        if content is None:
            continue
        if m.group("io").lower() == "input":
            if m.start() < sol_start:
                inp = content
        elif m.start() >= sol_end:
            out_after = content
        else:
            out_before = content
    return inp, out_after if out_after is not None else out_before


def _norm(s):
    lines = [x.rstrip() for x in s.replace("\r\n", "\n").split("\n")]
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


