"""Write simplescale/src/simplescale/harnesses/arv2.py from the lab's final prompt files.
python build_harness_assets.py --prompt plan_prompt_rX.txt --examples examples_rX.txt"""
import argparse, inspect, json
import arv2_plan as P
ap = argparse.ArgumentParser(); ap.add_argument("--prompt", required=True); ap.add_argument("--examples", required=True)
ap.add_argument("--out", default="/home/sgeng/scottg/pretrain/simplescale/src/simplescale/harnesses/arv2.py")
a = ap.parse_args()
plan = open(a.prompt).read()
examples = [e.strip() for e in open(a.examples).read().split("=====") if e.strip()]
src = f'''"""Active Reading v2 prompt assets and helpers for ``simplescale.harnesses.multisample:active_reading_v2``.

Generated by simplescale/runs/prompt_lab/arv2/build_harness_assets.py from the prompt lab's final version
({a.prompt}, {a.examples}, arv2_plan.py {P.VERSION}); see simplescale/runs/prompt_lab/arv2/iterations.md.

Stage 1 (plan, thinking on): PLAN asks for n document-specific prompts for alternative public web documents. Each
call gets per-prompt assignments (a length scaled to the source, a writing quality, a form + alternative drawn from
FORMS), one fictional worked example drawn from EXAMPLES, and, for later calls, the earlier prompts (PREVIOUS).
Stage 2 (execute, thinking off): exec_message wraps the source (as the writer's notes) and one prompt, after
sanitize_prompt rewrites references to the text / the source. finish_view markdown-strips a view (clean_markdown),
rewrites sentence-initial 'The text notes that X' to 'X' (repair_references) and checks it with reject_reason (placeholders, references to a source text, script switches,
degenerate repetition, verbatim copying); plan sections that are drafts rather than instructions are dropped
(bad_prompt).
"""
import random
import re

PLAN = {json.dumps(plan)}
PREVIOUS = {json.dumps(P.PREVIOUS)}
EXAMPLES = {json.dumps(examples, indent=1)}
EXEC = {json.dumps(P.EXEC)}
LENGTHS = {P.LENGTHS!r}
LENGTH_FRAC = {P.LENGTH_FRAC!r}
QUALITY = {P.QUALITY!r}
ROUGH_MAX_WORDS = {P.ROUGH_MAX_WORDS!r}
FORMS = {P.FORMS!r}
WORDS_PER_VIEW, MIN_VIEWS, MAX_VIEWS, PER_CALL = {P.WORDS_PER_VIEW}, {P.MIN_VIEWS}, {P.MAX_VIEWS}, {P.PER_CALL}

'''
for name in ["n_views", "_pick", "slots", "previous_block"]:
    src += inspect.getsource(getattr(P, name)) + "\n\n"
src += '''def plan_message(text, n, rng, examples=EXAMPLES, prev=None):
    """Stage-1 user message for n prompts; prev = earlier (title, prompt) pairs for this source."""
    ex = rng.choice(examples)
    return (PLAN.replace("{previous}", previous_block(prev, n) if prev else "").replace("{n}", str(n))
            .replace("{slots}", slots(text, n, rng)).replace("{examples}", ex).replace("{text}", text))


_HEAD = re.compile(r"^##(?!#)[ \\t]*(.*)$", re.M)


def split_prompts(reply):
    """(title, prompt) for each ``##`` section of a plan reply; empty sections dropped."""
    hs = list(_HEAD.finditer(reply))
    out = []
    for i, h in enumerate(hs):
        body = reply[h.end():hs[i + 1].start() if i + 1 < len(hs) else len(reply)].strip()
        if body:
            out.append((h.group(1).strip(), body))
    return out


'''
body = inspect.getsource(P)
src += body[body.index("# References to"):]
open(a.out, "w").write(src)
print("wrote", a.out)
